package com.example.py_damb2026ii.model;

public class UserAuthModel {
    private int id;
    private String username;
    private String rol;
    private boolean activo;

    public int getId() {
        return id;
    }

    public String getUsername() {
        return username;
    }

    public String getRol() {
        return rol;
    }

    public boolean isActivo() {
        return activo;
    }
}
