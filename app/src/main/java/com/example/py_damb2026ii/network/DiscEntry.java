package com.example.py_damb2026ii.network;

public class DiscEntry {
    public final int id;
    public final String precio;
    public final String titulo;
    public final String url;

    public DiscEntry(int id, String precio, String titulo, String url) {
        this.id = id;
        this.precio = precio;
        this.titulo = titulo;
        this.url = url;
    }
}
